#!/usr/bin/env node
/**
 * SKY CRED build — zero dependencies.
 *
 *   src/            ──copy──▶  dist/
 *   WEATHER_API_KEY ──────────▶ dist/js/env.js   (generated)
 *
 * Where the key comes from (first non-empty value wins):
 *   1. the process environment — Vercel project settings, CI, or `WEATHER_API_KEY=… npm run build`
 *   2. a local `.env` file (git-ignored)
 *
 * The key is inlined into client-side JavaScript, so every visitor of the site can read it.
 * `.env` keeps it out of Git; nothing in a backend-less app can keep it out of the browser.
 */
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const SRC_DIR = join(ROOT, 'src');
export const DIST_DIR = join(ROOT, 'dist');

const DEFAULT_BASE_URL = 'https://api.weatherapi.com/v1';
const PLACEHOLDER_KEY = 'your_weatherapi_key_here';

/** Minimal `.env` parser: KEY=value, optional quotes, `#` comments, optional `export ` prefix. */
export function parseDotEnv(text) {
  const values = {};
  for (const rawLine of String(text).split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).replace(/^export\s+/, '').trim();
    let value = line.slice(eq + 1).trim();
    const quoted =
      value.length >= 2 &&
      ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'")));
    value = quoted ? value.slice(1, -1) : value.replace(/\s+#.*$/, '');
    if (key) values[key] = value;
  }
  return values;
}

async function copyDir(from, to) {
  await mkdir(to, { recursive: true });
  for (const entry of await readdir(from, { withFileTypes: true })) {
    const source = join(from, entry.name);
    const target = join(to, entry.name);
    if (entry.isDirectory()) await copyDir(source, target);
    else if (entry.isFile()) await copyFile(source, target);
  }
}

export async function build({ log = console.log } = {}) {
  const dotEnvPath = join(ROOT, '.env');
  const fileEnv = existsSync(dotEnvPath) ? parseDotEnv(await readFile(dotEnvPath, 'utf8')) : {};
  const pick = (name) => String(process.env[name] || fileEnv[name] || '').trim();

  const apiKey = pick('WEATHER_API_KEY');
  const baseUrl = (pick('WEATHER_API_BASE_URL') || DEFAULT_BASE_URL).replace(/\/+$/, '');

  if (!apiKey || apiKey === PLACEHOLDER_KEY) {
    throw new Error(
      'WEATHER_API_KEY is not set. Copy .env.example to .env and add your WeatherAPI key, ' +
        'or set the variable in your hosting environment.'
    );
  }

  await rm(DIST_DIR, { recursive: true, force: true });
  await copyDir(SRC_DIR, DIST_DIR);

  const config = JSON.stringify({ weatherApiKey: apiKey, weatherApiBaseUrl: baseUrl }, null, 2);
  const envModule = [
    '// Generated by scripts/build.mjs — do not edit, do not commit.',
    '// This value ships to the browser and is visible to every visitor: it is not a secret.',
    `export const CONFIG = Object.freeze(${config});`,
    '',
  ].join('\n');
  await writeFile(join(DIST_DIR, 'js', 'env.js'), envModule, 'utf8');

  log(`[build] dist/ ready — WeatherAPI base ${baseUrl}, API key loaded`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  build().catch((error) => {
    console.error(`[build] ${error.message}`);
    process.exit(1);
  });
}
